package com.EvoGrid.common.game;

/** Роль способности: у каждого вида ровно по одной в слотах 1–4. */
public enum AbilityCategory {
    /** Слот 1: обычная атака без перезарядки. */
    BASIC,
    /** Слот 2: особая атака своей стихии, часто со статусом. */
    SPECIAL,
    /** Слот 3: блок или уворот. */
    DEFENSE,
    /** Слот 4: лечение, усиление или контроль. */
    UTILITY
}
