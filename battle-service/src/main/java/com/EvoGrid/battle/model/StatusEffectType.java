package com.EvoGrid.battle.model;

public enum StatusEffectType {
    NONE,
    // Периодический урон и контроль (негативные статусы)
    BURN,               // Горение: 8% от MaxHP в конце хода (2 хода)
    POISON,             // Яд: 10% от MaxHP в конце хода (3 хода)
    SLEEP,              // Сон: пропуск хода (1 ход)
    STUN,               // Оглушение / Сбивание с ног: пропуск хода (1 ход)
    SLOW,               // Замедление: снижение скорости на 35% (2 хода)
    BLIND,              // Ослепление: снижение точности на 35% (2 хода)

    // Защитные стойки (на 1 раунд / следующий удар)
    BLOCK,              // Снижение входящего прямого урона на X%
    EVASION,            // Уворот: 65% шанс промаха врага
    SHELL_BARRIER,      // Ракушечный барьер: полное поглощение следующего удара
    CRIT_IMMUNE,        // Защита от критического урона (2 хода)
    CC_IMMUNE,          // Защита от эффектов контроля и дебаффов (2 хода)

    // Боевые баффы и спецэффекты
    REGEN,              // Регенерация: +10% MaxHP в конце хода (3 хода)
    ATK_UP,             // Повышение атаки на 30% (2 хода)
    DEF_UP,             // Повышение защиты на 35% (2 хода)
    THORNS,             // Шипы: возврат 10% MaxHP атакующему (2 хода)
    RAGE_SPEED_PIERCE,  // Удвоение скорости (x2) + игнорирование блока цели (2 хода)
    NEXT_HIT_BURN,      // Следующая атака гарантированно поджигает цель
    WATER_BOOST,        // Следующая водная атака наносит +35% урона
    GUARANTEED_CRIT,    // Следующая атака наносит гарантированный крит (x1.5)
    CLEANSE             // Мгновенное снятие негативных статусов
}